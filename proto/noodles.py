"""Прототип: лапша — нарезка полос (src/NeonTools.bas, раздел @@NOODLEGEO).

N полос длиной L и шириной W: N + 1 горизонтальных резов через W и два вертикальных отреза на
концах. Резы выходят за край — хвосты, чтобы полоса отделилась полностью: горизонтальные — за
отрезы на over_h, отрезы — за крайние горизонтальные на over_v (лазеру хватает миллиметра,
фрезе нужно больше). Порядок резки: горизонтальные сверху вниз
зигзагом (первый — слева направо, дальше направления чередуются), затем отрезы — тоже по ходу:
сначала на той стороне, где кончился последний горизонтальный (снизу вверх), потом на другой
(сверху вниз). Объекты создаются в обратном порядке: в диспетчере объектов (сверху вниз) и при
экспорте в обратную сторону порядок совпадает с образцом автора — вертикальные в конце списка.
Координаты CorelDRAW (y вверх), центр блока — (cx, cy).
"""


def noodles(cx, cy, L, W, N, over_h, over_v):
    """-> отрезки (x1, y1, x2, y2) в порядке создания (последний — первый рез)."""
    xl = cx - L / 2
    xr = cx + L / 2
    yt = cy + N * W / 2
    yb = yt - N * W
    cut = []
    for k in range(N + 1):
        y = yt - k * W
        if k % 2 == 0:
            cut.append((xl - over_h, y, xr + over_h, y))
        else:
            cut.append((xr + over_h, y, xl - over_h, y))
    # последний горизонтальный кончился справа (N чётное) или слева
    first, second = (xr, xl) if N % 2 == 0 else (xl, xr)
    cut.append((first, yb - over_v, first, yt + over_v))
    cut.append((second, yt + over_v, second, yb - over_v))
    return list(reversed(cut))
