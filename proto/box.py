"""Прототип: кубик (короб) под фрезеровку — развёртка из 6 деталей (src/NeonTools.bas, раздел @@BOXGEO).

Наружные размеры L × W × H (длина, ширина, высота), материал толщиной t. Детали соединяются в
четверть: на внутренней стороне у края выбирается ступенька шириной s = t + c (толщина стенки +
зазор c, обычно 0,2 мм) и глубиной t − e, у края остаётся e — «высота ступеньки».
  - крышка и дно — 2 шт L × W, четверть по всему периметру (замкнутый контур, отступ s от края);
  - перед и зад — 2 шт L × (H − 2e): стоят в четвертях крышки и дна (на каждом конце уходят на t − e,
    наружу остаётся бортик e), четверть вдоль двух боковых краёв — линии на s от края, с выходом
    за край o (чтобы фреза прошла насквозь);
  - бока — 2 шт (W − 2e) × (H − 2e), гладкие: стоят в четвертях переда, зада, крышки и дна.
Пример автора: 500 × 500 × 500, t = 5, e = 2, c = 0,2, o = 2 — крышка 500 × 500 с контуром 489,6,
перед 500 × 496 с линиями длиной 500, бок 496 × 496.

Развёртка крестом (y вверх, центр блока — (cx, cy)): по центру столбиком сверху вниз крышка, перед,
дно, зад; бока — слева и справа от дна (по развёртке: x — высота стенки, y — ширина кубика).
Зазор между деталями g = 20 + o (выход линий не залезает на соседа).
Детали — в порядке создания: крышка, перед, дно, зад, левый бок, правый бок.
"""


def box(cx, cy, L, W, H, t, e, c, o):
    """-> (panels, red). panels: (x, y, w, h, kind) — левый нижний угол и размер, kind 0 крышка/дно,
    1 стенка с четвертью по бокам, 2 гладкая стенка. red: (panel, type, x1, y1, x2, y2) — type 0
    прямоугольник по углам, 1 отрезок."""
    s = t + c
    hw = H - 2 * e          # высота стенок
    ws = W - 2 * e          # ширина боков
    g = 20 + o
    tot_h = W + g + hw + g + W + g + hw
    yt = cy + tot_h / 2
    x0 = cx - L / 2
    panels = []
    y = yt - W
    panels.append((x0, y, L, W, 0))                 # крышка
    y = y - g - hw
    panels.append((x0, y, L, hw, 1))                # перед
    y = y - g - W
    panels.append((x0, y, L, W, 0))                 # дно
    yb = y
    y = y - g - hw
    panels.append((x0, y, L, hw, 1))                # зад
    ys = yb + W / 2 - ws / 2                        # бока — по середине дна
    panels.append((x0 - g - hw, ys, hw, ws, 2))     # левый бок
    panels.append((x0 + L + g, ys, hw, ws, 2))      # правый бок
    red = []
    for i in range(len(panels)):
        x, y, w, h, k = panels[i]
        if k == 0:
            red.append((i, 0, x + s, y + s, x + w - s, y + h - s))
        elif k == 1:
            red.append((i, 1, x + s, y - o, x + s, y + h + o))
            red.append((i, 1, x + w - s, y - o, x + w - s, y + h + o))
    return panels, red


def check(L, W, H, t, e, c, o):
    """Пустая строка — можно строить; иначе что не так (как проверяет окно)."""
    if not (10 <= L <= 10000 and 10 <= W <= 10000 and 10 <= H <= 10000):
        return 'размеры 10–10000 мм'
    if not (0 < t <= 100):
        return 'толщина 0–100'
    if not (0 < e < t):
        return 'ступенька больше 0 и меньше толщины'
    if not (0 <= c <= 10) or not (0 <= o <= 100):
        return 'зазор 0–10, выход 0–100'
    s = t + c
    if 2 * s >= L or 2 * s >= W or 2 * s >= H:
        return 'четверть не помещается'
    return ''


